  let current = "pt";

  function detectLocale() {
    const nav = (navigator.language || "pt").slice(0, 2).toLowerCase();
    if (LOCALES.includes(nav)) return nav;
    return "pt";
  }

  function setLocale(loc) {
    const next = LOCALES.includes(loc) ? loc : "pt";
    current = next;
    document.documentElement.lang = LOCALE_TAGS[next] || "pt-BR";
    return next;
  }

  function getLocale() {
    return current;
  }

  function localeTag() {
    return LOCALE_TAGS[current] || "pt-BR";
  }

  function t(key, params) {
    const bag = STR[current] || STR.pt;
    let s = bag[key] != null ? bag[key] : STR.pt[key] != null ? STR.pt[key] : key;
    if (params && typeof params === "object") {
      Object.keys(params).forEach((k) => {
        s = s.replace(new RegExp("\\{" + k + "\\}", "g"), String(params[k]));
      });
    }
    return s;
  }

