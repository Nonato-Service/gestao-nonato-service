  function normalizeLocale(raw) {
    const s = String(raw || "").trim();
    if (s === "en-US") return "en";
    if (LOCALES.includes(s)) return s;
    return "pt-BR";
  }

  function format(str, params) {
    if (!params) return str;
    return String(str).replace(/\{(\w+)\}/g, (_, k) =>
      params[k] !== undefined && params[k] !== null ? String(params[k]) : ""
    );
  }

  function t(locale, key, params) {
    const loc = normalizeLocale(locale);
    const bundle = bundles[loc] || bundles["pt-BR"];
    const fallback = bundles["pt-BR"];
    const raw = bundle[key] ?? fallback[key] ?? key;
    return format(raw, params);
  }

  function localeTag(locale) {
    const loc = normalizeLocale(locale);
    if (loc === "pt-BR") return "pt-BR";
    if (loc === "en") return "en-GB";
    if (loc === "es") return "es-ES";
    if (loc === "fr") return "fr-FR";
    if (loc === "it") return "it-IT";
    if (loc === "de") return "de-DE";
    return "pt-BR";
  }

  global.NonatoBibliaI18n = { normalizeLocale, t, localeTag, LOCALES };
